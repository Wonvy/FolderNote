"""Regenerate the offline initial table from the pinned MIT-licensed pinyin-data."""
from pathlib import Path
import hashlib
import unicodedata
import urllib.request

REVISION = "fe29ad32bdf352b31a02b9936e537f575432e9a6"
BASE = f"https://raw.githubusercontent.com/mozillazg/pinyin-data/{REVISION}/"
root = Path(__file__).resolve().parents[1]
directory = root / "third_party" / "pinyin-data"
directory.mkdir(parents=True, exist_ok=True)
source = urllib.request.urlopen(BASE + "pinyin.txt", timeout=30).read()
license_text = urllib.request.urlopen(BASE + "LICENSE", timeout=30).read()
(directory / "LICENSE").write_bytes(license_text)
entries = []
for line in source.decode("utf-8").splitlines():
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    point, readings = line.split(":", 1)
    mask = 0
    for reading in readings.strip().split(","):
        first = unicodedata.normalize("NFD", reading.strip())[0].lower()
        if "a" <= first <= "z":
            mask |= 1 << (ord(first) - ord("a"))
    if mask:
        entries.append((int(point.removeprefix("U+"), 16), mask))
entries.sort()
assert len(entries) > 40000 and len({x[0] for x in entries}) == len(entries)
header = f"// Generated by tools/generate_pinyin_initials.py. Do not edit.\n// pinyin-data {REVISION}; MIT license in third_party/pinyin-data/LICENSE.\n"
lines = ["{" + f"0x{point:X}, 0x{mask:X}" + "}," for point, mask in entries]
(root / "src" / "pinyin_initials.inc").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
(directory / "README.md").write_text(
    f"# pinyin-data\n\nSource: https://github.com/mozillazg/pinyin-data/tree/{REVISION}\n\n"
    f"Input `pinyin.txt` SHA-256: `{hashlib.sha256(source).hexdigest()}`.\n\n"
    "The generated table keeps every reading's first letter, including polyphonic and traditional characters. "
    "It is compiled into the program; no network request is made while matching. "
    "The MIT license is embedded as resource 302 in distributed executables and DLLs.\n", encoding="utf-8")
print(f"Generated {len(entries)} character mappings.")
